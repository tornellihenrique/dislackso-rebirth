package livekit

import (
	"fmt"
	"os"
	"path/filepath"

	"go.yaml.in/yaml/v3"
)

// ServerOptions describe the LiveKit server the hub runs as a sidecar.
type ServerOptions struct {
	Port    int
	UDPPort int
	TCPPort int
	APIKey  string
	// WebhookURL is the hub's webhook endpoint on localhost.
	WebhookURL string
	// ExternalIP discovers the public address over STUN; LiveKit refuses to
	// start when STUN is unreachable.
	ExternalIP bool
	LogLevel   string
}

// STUNServers find the host's public address and are handed to clients.
var STUNServers = []string{"stun.cloudflare.com:3478", "stun.l.google.com:19302"}

// The server rejects unknown keys, so the field names follow LiveKit's
// configuration exactly.
type serverConfig struct {
	Port          int           `yaml:"port"`
	BindAddresses []string      `yaml:"bind_addresses"`
	RTC           rtcConfig     `yaml:"rtc"`
	Room          roomConfig    `yaml:"room"`
	Webhook       webhookConfig `yaml:"webhook"`
	Logging       loggingConfig `yaml:"logging"`
}

type rtcConfig struct {
	UDPPort       int  `yaml:"udp_port"`
	TCPPort       int  `yaml:"tcp_port"`
	UseExternalIP bool `yaml:"use_external_ip"`
	// Hosts behind NAT usually cannot reach their own public address.
	SkipExternalIPValidation bool     `yaml:"skip_external_ip_validation"`
	AdvertiseInternalIP      bool     `yaml:"advertise_internal_ip"`
	STUNServers              []string `yaml:"stun_servers"`
}

type roomConfig struct {
	AutoCreate       bool `yaml:"auto_create"`
	EmptyTimeout     int  `yaml:"empty_timeout"`
	DepartureTimeout int  `yaml:"departure_timeout"`
}

type webhookConfig struct {
	APIKey string   `yaml:"api_key"`
	URLs   []string `yaml:"urls"`
}

type loggingConfig struct {
	Level string `yaml:"level"`
	JSON  bool   `yaml:"json"`
}

// ServerConfig renders livekit.yaml. The API secret is not in it: the
// sidecar gets the keys through KeysEnv.
func ServerConfig(o ServerOptions) ([]byte, error) {
	level := o.LogLevel
	if level == "" {
		level = "info"
	}
	c := serverConfig{
		Port: o.Port,
		// Signaling stays private; clients reach it through the hub's /lk proxy.
		BindAddresses: []string{"127.0.0.1"},
		RTC: rtcConfig{
			UDPPort:                  o.UDPPort,
			TCPPort:                  o.TCPPort,
			UseExternalIP:            o.ExternalIP,
			SkipExternalIPValidation: o.ExternalIP,
			AdvertiseInternalIP:      o.ExternalIP,
			STUNServers:              STUNServers,
		},
		Room:    roomConfig{AutoCreate: true, EmptyTimeout: 30, DepartureTimeout: 20},
		Webhook: webhookConfig{APIKey: o.APIKey, URLs: []string{o.WebhookURL}},
		Logging: loggingConfig{Level: level, JSON: true},
	}
	out, err := yaml.Marshal(c)
	if err != nil {
		return nil, fmt.Errorf("render livekit config: %w", err)
	}
	return append([]byte("# Generated by the hub on every start. Do not edit.\n"), out...), nil
}

// KeysEnv passes the API key pair to livekit-server without writing the
// secret to disk or the command line.
func KeysEnv(key, secret string) string { return "LIVEKIT_KEYS=" + key + ": " + secret }

// WriteServerConfig renders the config into path, replacing what is there.
func WriteServerConfig(path string, o ServerOptions) error {
	data, err := ServerConfig(o)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return fmt.Errorf("create livekit config dir: %w", err)
	}
	if err := os.WriteFile(path, data, 0o600); err != nil {
		return fmt.Errorf("write livekit config: %w", err)
	}
	return nil
}
